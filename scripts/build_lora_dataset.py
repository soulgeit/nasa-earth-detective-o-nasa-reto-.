def load_places() -> tuple[list[str], list[str]]:
    """(Spanish, English) place names, from the gazetteer when available."""
    if os.path.exists(GAZETTEER):
        with open(GAZETTEER, encoding="utf-8") as fh:
            data = json.load(fh)
        peru = [c["name"] for c in data["cities"] if c["country"] == "PE"][:120]
        world = [c["name"] for c in data["cities"] if c["country"] != "PE"][:200]
        places = sorted(set(peru + world))
        return places, places
    return PROVISIONAL_PLACES, EN_PLACES


