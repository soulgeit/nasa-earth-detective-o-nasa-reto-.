def load_variables() -> dict[str, dict[str, Any]]:
    """variable_id -> {name_es, name_en, def_es, def_en, unit, sphere}."""
    out: dict[str, dict[str, Any]] = {}
    if os.path.exists(CATALOG):
        with open(CATALOG, encoding="utf-8") as fh:
            catalog = json.load(fh)
        for card in catalog["variables"]:
            out[card["id"]] = {
                "name_es": card["names"]["es"],
                "name_en": card["names"]["en"],
                "def_es": card["simple_definition"]["es"],
                "def_en": card["simple_definition"]["en"],
                "unit": card["unit"],
                "sphere": card["sphere"],
            }
        return out

    with open(SEED, encoding="utf-8") as fh:
        seed = json.load(fh)
    for entry in seed["live"]:
        out[entry["id"]] = {
            "name_es": entry.get("power_longname", entry["id"]),
            "name_en": entry.get("power_longname", entry["id"]),
            "def_es": "",
            "def_en": "",
            "unit": entry["unit"],
            "sphere": entry["sphere"],
        }
    return out


