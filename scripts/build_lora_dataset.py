def candidate_line(vid: str, variables: dict[str, dict], lang: str) -> str:
    info = variables[vid]
    if lang == "es":
        name, definition, unit = info["name_es"], info["def_es"], info["unit"]
    else:
        name, definition, unit = info["name_en"], info["def_en"], info["unit"]
    definition = (definition or "").rstrip(".")
    if len(definition) > 110:
        definition = definition[:107].rsplit(" ", 1)[0] + "..."
    return f"- {vid}: {name} ({unit}) - {definition}"


def build_user_message(question: str, candidates: list[str], variables: dict, lang: str) -> str:
    lines = [f"QUESTION: {question}", "CANDIDATES:"]
    for vid in candidates:
        lines.append(candidate_line(vid, variables, lang))
    return "\n".join(lines)


