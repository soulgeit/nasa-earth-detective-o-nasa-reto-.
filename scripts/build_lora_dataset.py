def normalize_text(text: str) -> str:
    text = unicodedata.normalize("NFD", text.lower())
    text = "".join(c for c in text if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9 ]+", " ", text)


def word_jaccard(a: str, b: str) -> float:
    sa, sb = set(normalize_text(a).split()), set(normalize_text(b).split())
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / len(sa | sb)


def choose_distractors(rng: random.Random, correct: str, variables: dict) -> list[str]:
    sphere = variables[correct]["sphere"]
    same = [v for v in variables if v != correct and variables[v]["sphere"] in DISTRACTOR_SPHERES.get(sphere, [])]
    other = [v for v in variables if v != correct and v not in same]
    rng.shuffle(same)
    rng.shuffle(other)
    picked = same[:2]
    picked += other[: max(0, 5 - len(picked))]
    if len(picked) < 5:
        rest = [v for v in variables if v != correct and v not in picked]
        picked += rest[: 5 - len(picked)]
    return picked[:5]


def apply_noise(rng: random.Random, text: str, lang: str, keep_words: list[str] | None = None) -> str:
    """British spelling of 'noise': accent stripping, lowercasing and a typo.

    Words in `keep_words` (place names) are never typo-ed, because the plan
    must copy them literally; accent and case noise is restored afterwards.
    """
    keep: set[str] = set()
    for w in keep_words or []:
        if w:
            keep.update(normalize_text(w).split())
    roll = rng.random()
    if roll < 0.20:
        text = "".join(
            c for c in unicodedata.normalize("NFD", text)
            if unicodedata.category(c) != "Mn"
        )
    if roll < 0.10:
        text = text.lower()
    if 0.10 <= roll < 0.20:
        words = text.split()
        candidates = [
            i for i, w in enumerate(words)
            if len(w) > 3 and not (set(normalize_text(w).split()) & keep)
        ]
        if candidates:
            i = rng.choice(candidates)
            w = words[i]
            j = rng.randrange(1, len(w) - 1)
            words[i] = w[:j] + w[j + 1:] if rng.random() < 0.5 else w[:j] + w[j] + w[j:]
            text = " ".join(words)
    return text


def restore_literal(text: str, value: str) -> str:
    """Ensure `value` appears with its exact spelling in `text`, matching
    case- and accent-insensitively (noise may have lowercased or stripped
    accents). Returns the text unchanged when the value is not present."""
    if not value or value in text:
        return text

    def fold(s: str) -> tuple[str, list[int]]:
        chars: list[str] = []
        index: list[int] = []
        for i, ch in enumerate(unicodedata.normalize("NFD", s)):
            if unicodedata.category(ch) == "Mn":
                continue
            chars.append(ch.lower())
            index.append(i)
        return "".join(chars), index

    text_nfd = unicodedata.normalize("NFD", text)
    value_nfd = unicodedata.normalize("NFD", value)
    folded_text, index = fold(text_nfd)
    folded_value, _ = fold(value_nfd)
    pos = folded_text.find(folded_value)
    if pos < 0:
        return text
    start = index[pos]
    end = index[pos + len(folded_value) - 1] + 1
    restored = text_nfd[:start] + value_nfd + text_nfd[end:]
    return unicodedata.normalize("NFC", restored)


def make_example(rng, lang, intent, template, vid, place, place_b, years, hypothesis,
                 variables, template_id, source="template"):
    q = template.format(
        variable=pick_topic(rng, vid, lang) or vid,
        place=place or "",
        place_b=place_b or "",
        year0=years[0] if years else "",
        year1=years[1] if years else "",
        n=years[2] if years and len(years) > 2 else "",
    )
    q = apply_noise(rng, q, lang, keep_words=[p for p in (place, place_b) if p])
    # Noise may lowercase or strip accents; the place must stay literal in the
    # question because the contract requires copying it exactly.
    for place_value in (place, place_b):
        if place_value:
            q = restore_literal(q, place_value)
    candidates = choose_distractors(rng, vid, variables)
    if intent == "no_match":
        candidates = [c for c in candidates if c != vid][:5]
        gold: list[str] = []
    else:
        candidates = candidates + [vid]
        rng.shuffle(candidates)
        gold = [vid]
    user = build_user_message(q, candidates, variables, lang)
    # The place must appear literally in the question: pick from the template's
    # placeholders, not from noise-free text. apply_noise never alters words,
    # so plan.place matches `q`.
    plan = make_plan(intent, vid if intent != "no_match" else None, place, place_b,
                     years[0] if years else None, years[1] if years else None,
                     years[2] if years and len(years) > 2 else None,
                     hypothesis, lang)
    return {
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user},
            {"role": "assistant", "content": json.dumps(plan, ensure_ascii=False)},
        ],
        "meta": {
            "lang": lang, "intent": intent, "gold": gold,
            "template_id": template_id, "source": source,
        },
    }


