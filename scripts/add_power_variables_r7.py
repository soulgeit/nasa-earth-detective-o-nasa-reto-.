    existing = {c["id"] for c in payload["variables"]}
    planned = {c["id"] for c in payload.get("planned", [])}
    added = []
    for new in NEW_CARDS:
        if new["id"] in existing or new["id"] in planned:
            continue
        payload["variables"].append(new)
        added.append(new["id"])
    if added:
        payload["generated_at"] = "2026-11-15"
        CATALOG.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"added {len(added)}: {', '.join(added) or '-'}; catalogue now has {len(payload['variables'])} variables")
    return 0


